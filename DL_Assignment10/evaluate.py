"""Evaluate the saved CNN on ESC-50 fold 5 and save metrics/artifacts."""
import json
from pathlib import Path

import librosa
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch
from sklearn.metrics import accuracy_score, precision_recall_fscore_support, classification_report, confusion_matrix, ConfusionMatrixDisplay
from torch.utils.data import Dataset, DataLoader

from src.audio_utils import waveform_to_logmel, SAMPLE_RATE
from src.model import AudioCNN

ROOT = Path(__file__).resolve().parent
DATASET = ROOT / "data" / "ESC-50"
MODEL_PATH = ROOT / "models" / "audio_cnn.pt"
RESULTS = ROOT / "results"


class TestDataset(Dataset):
    def __init__(self, frame, classes):
        self.frame = frame.reset_index(drop=True)
        self.classes = classes
        self.class_to_idx = {name: i for i, name in enumerate(classes)}
    def __len__(self):
        return len(self.frame)
    def __getitem__(self, idx):
        row = self.frame.iloc[idx]
        waveform, _ = librosa.load(DATASET / "audio" / row["filename"], sr=SAMPLE_RATE, mono=True, duration=5.0)
        return waveform_to_logmel(waveform), self.class_to_idx[row["category"]]


def main():
    if not MODEL_PATH.exists():
        raise SystemExit("Trained model not found. Run `python train.py` first.")
    metadata = pd.read_csv(DATASET / "meta" / "esc50.csv")
    checkpoint = torch.load(MODEL_PATH, map_location="cpu", weights_only=False)
    classes = checkpoint["classes"]
    test_frame = metadata[metadata["fold"] == 5]
    loader = DataLoader(TestDataset(test_frame, classes), batch_size=16, shuffle=False, num_workers=0)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = AudioCNN(num_classes=len(classes)).to(device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()
    y_true, y_pred = [], []
    with torch.no_grad():
        for features, labels in loader:
            preds = model(features.to(device)).argmax(1).cpu().numpy()
            y_pred.extend(preds.tolist())
            y_true.extend(labels.numpy().tolist())

    accuracy = accuracy_score(y_true, y_pred)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="macro", zero_division=0
    )
    metrics = {
        "test_samples": len(y_true),
        "accuracy": float(accuracy),
        "macro_precision": float(precision),
        "macro_recall": float(recall),
        "macro_f1": float(f1),
        "test_fold": 5,
        "note": "Metrics generated by this local run; do not treat as expected or guaranteed results."
    }
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    (RESULTS / "classification_report.txt").write_text(
        classification_report(y_true, y_pred, labels=list(range(len(classes))), target_names=classes, zero_division=0),
        encoding="utf-8"
    )
    cm = confusion_matrix(y_true, y_pred, labels=list(range(len(classes))))
    fig, ax = plt.subplots(figsize=(18, 18))
    display = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=classes)
    display.plot(ax=ax, xticks_rotation=90, colorbar=False, include_values=False)
    ax.set_title("ESC-50 Test Fold Confusion Matrix")
    fig.tight_layout()
    fig.savefig(RESULTS / "confusion_matrix.png", dpi=160)
    plt.close(fig)

    print("Test results (ESC-50 fold 5):")
    for key, value in metrics.items():
        if isinstance(value, float):
            print(f"{key}: {value:.4f}")
        else:
            print(f"{key}: {value}")
    print(f"Artifacts saved in: {RESULTS}")


if __name__ == "__main__":
    main()
